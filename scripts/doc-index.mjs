#!/usr/bin/env node
// Generates docs/DOCUMENTATION-INDEX.md: one list of every tracked document, so no file is named nowhere.
//
//   node scripts/doc-index.mjs            write docs/DOCUMENTATION-INDEX.md
//   node scripts/doc-index.mjs --check    exit 1 when the committed index is stale
//
// Scope: Markdown files at the repository root and every tracked file under docs/ except the index itself.
// Titles come from the first "# " heading. Generated from `git ls-files`, so untracked files never appear.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, posix } from 'node:path';

const INDEX = 'docs/DOCUMENTATION-INDEX.md';
const check = process.argv.includes('--check');

const tracked = execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 })
  .split('\0')
  .filter(Boolean);
const files = tracked
  .filter((f) => f !== INDEX && existsSync(f))
  .filter((f) => (!f.includes('/') && f.endsWith('.md')) || f.startsWith('docs/'))
  .sort((a, b) => a.localeCompare(b, 'en'));

const title = (file) => {
  if (!file.endsWith('.md')) return '';
  const first = readFileSync(file, 'utf8')
    .split('\n')
    .find((line) => line.startsWith('# '));
  return first ? first.slice(2).trim().replace(/\|/g, '\\|') : '';
};
const link = (file) => `[${posix.basename(file)}](${posix.relative(dirname(INDEX), file) || file})`;

const groups = new Map();
for (const file of files) {
  const dir = file.includes('/') ? posix.dirname(file) : '(repository root)';
  if (!groups.has(dir)) groups.set(dir, []);
  groups.get(dir).push(file);
}

const lines = [
  '# Documentation index',
  '',
  'Every Markdown file at the repository root and every tracked file under `docs/`, grouped by folder. This file is generated by `scripts/doc-index.mjs` (`pnpm run docs:index`) and checked in CI (`pnpm run docs:index:check`); do not edit it by hand. The current status of the project (version, hosting, last verified run) is stated once, at the top of [HANDOVER.md](../HANDOVER.md).',
  '',
  `${files.length} files in ${groups.size} folders.`,
  '',
];
for (const [dir, list] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  lines.push(`## ${dir === '(repository root)' ? dir : `\`${dir}/\``}`, '', '| File | Title |', '|---|---|');
  for (const file of list) lines.push(`| ${link(file)} | ${title(file)} |`);
  lines.push('');
}
const next = lines.join('\n');

if (check) {
  const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : '';
  if (current !== next) {
    console.error(`${INDEX} is stale; run "node scripts/doc-index.mjs" and commit the result.`);
    process.exit(1);
  }
  console.log(`${INDEX} is current (${files.length} files).`);
} else {
  writeFileSync(INDEX, next);
  console.log(`wrote ${INDEX}: ${files.length} files in ${groups.size} folders`);
}
